local BINDINGS = {
    food = "BINDING_NAME_CLICK ReFoodFoodButton:LeftButton",
    drink = "BINDING_NAME_CLICK ReFoodDrinkButton:LeftButton",
    rest = "BINDING_NAME_CLICK ReFoodRestButton:LeftButton",
    buff = "BINDING_NAME_CLICK ReFoodBuffButton:LeftButton",
}

local function Resolve(choice)
    if choice and STRINGS[choice] then return choice end
    local gameLocale = GetLocale()
    return STRINGS[gameLocale] and gameLocale or "enUS"
end

function ns.ApplyLanguage(choice)
    local code = Resolve(choice)
    wipe(L)
    for key, text in pairs(STRINGS.enUS) do
        L[key] = text
    end
    if code ~= "enUS" then
        for key, text in pairs(STRINGS[code]) do
            L[key] = text
        end
    end
    BINDING_HEADER_REFOOD = ns.TITLE
    for key, global in pairs(BINDINGS) do
        _G[global] = L["BINDING_" .. key]
    end
    ns.Fire("LOCALE_CHANGED")
end

ns.ApplyLanguage("auto")

ns.Listen("DB_READY", function()
    ns.ApplyLanguage(ns.db.locale)
end)

ns.Listen("SETTING_CHANGED", function(key)
    if key == nil or key == "locale" then
        ns.ApplyLanguage(ns.db.locale)
    end
end)
